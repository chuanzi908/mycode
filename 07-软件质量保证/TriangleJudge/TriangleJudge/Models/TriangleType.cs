namespace Wbc.SoftwareQuality.Triangle.Models
{
    /// <summary>
    /// 三角形的形状类型。
    /// </summary>
    public enum TriangleType
    {
        /// <summary>
        /// 三条边不能构成三角形。
        /// </summary>
        NotTriangle = 0,

        /// <summary>
        /// 普通三角形（三边互不相等）。
        /// </summary>
        Scalene = 1,

        /// <summary>
        /// 等腰三角形（仅有两边相等）。
        /// </summary>
        Isosceles = 2,

        /// <summary>
        /// 等边三角形（三边相等）。
        /// </summary>
        Equilateral = 3
    }
}
