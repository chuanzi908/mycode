import pandas as pd

# 1. 创建和你截图完全一致的测试数据（DataFrame）
data = {
    '分区': ['华东', '华南', '华北', '华东', '华南', '华北', '华东', '华南', '华北'],
    '商品': ['手机', '手机', '手机', '电脑', '电脑', '电脑', '平板', '平板', '平板'],
    '一季度': [100, 80, 50, 200, 150, 100, 150, 100, 80],
    '二季度': [110, 90, 60, 210, 160, 110, 160, 110, 90],
    '三季度': [120, 100, 70, 220, 170, 120, 170, 120, 100],
    '四季度': [130, 110, 80, 230, 180, 130, 180, 130, 110]
}

df = pd.DataFrame(data)

# 2. 按'分区'列分组
myGroup = df.groupby('分区')

# 3. 分组聚合：一季度求和
myGroup1 = myGroup.agg({'一季度':'sum'})
print("=== 一季度分区销售总和 ===")
print(myGroup1)
print("\n")

# 4. 多列、多种聚合方式
myGroup2 = myGroup.agg({
    '一季度': ['sum', 'max'],
    '二季度': ['mean', 'min'],
    '三季度': ['mean']
})
print("=== 多列多方式聚合结果 ===")
print(myGroup2)
print("\n")

# 5. transform：按分组计算均值，保持原表行数
myGroup3 = myGroup['四季度'].transform('mean')
print("=== 四季度分区均值（广播到每一行）===")
print(myGroup3)